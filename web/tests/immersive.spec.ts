import {test,expect} from "@playwright/test";

test("first-person walking, map travel, single-agent follow and exit",async({page,request},testInfo)=>{
  test.setTimeout(120000);
  const response=await request.get('/api/v1/world');expect(response.ok()).toBeTruthy();
  const original=await response.json();
  const center=original.geography?.centerX??0,start=`${center.toFixed(1)}, 8.0`;
  const resident=(id:string,name:string,x:number)=>({id,name,x,z:8,activity:'MOVE',location:'road',home:'apt-101',status:'active',occupation:'Resident',description:'Test resident',fixture:true});
  const world={...original,agents:[resident('test-a','Mira',center),resident('test-b','Orion',center+12)],minute:720,weather:'Clear'};
  await page.route('**/api/v1/world',r=>r.fulfill({json:world}));
  await page.route('**/api/v1/auth/me',r=>r.fulfill({json:{id:'test-owner',email:'owner@example.test'}}));
  await page.route('**/api/v1/owner/agents',r=>r.fulfill({json:[world.agents[0]]}));
  await page.route('**/api/config',r=>r.fulfill({json:{webSocketUrl:'ws://localhost:3000/ws/immersive-test'}}));
  let update:((value:unknown)=>void)|undefined;
  await page.routeWebSocket('**/ws/immersive-test',socket=>{update=value=>socket.send(JSON.stringify(value));socket.send(JSON.stringify(world));});
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await expect(page.getByLabel('Map zoom')).toHaveText('100%',{timeout:30000});await page.getByRole('button',{name:'Enter the world'}).click();
  const dialog=page.getByRole('dialog',{name:'Explore New Eden in first person'});
  await expect(dialog).toBeVisible({timeout:30000});await expect(dialog.locator('canvas')).toBeVisible({timeout:30000});
  await expect(dialog.locator('canvas')).toHaveAttribute('data-controls-ready','true',{timeout:30000});
  const position=page.getByLabel('Your world position');await expect(position).toHaveText(start);
  const zoom=page.getByLabel('View zoom',{exact:true}),canvas=dialog.locator('canvas');
  const checkZoom=async(percent:string)=>{await expect(zoom).toHaveText(percent+'%');await expect(canvas).toHaveAttribute('data-view-zoom',percent);};
  await checkZoom('100');
  await page.getByRole('button',{name:'Zoom in view',exact:true}).click();await checkZoom('120');

  await expect(position).toHaveText(start);
  await page.getByRole('button',{name:'Zoom out view',exact:true}).click();await checkZoom('100');
  await canvas.hover();await page.mouse.wheel(0,-180);await expect.poll(async()=>Number(await canvas.getAttribute('data-view-zoom'))).toBeGreaterThan(120);
  await page.mouse.wheel(0,300);await expect.poll(async()=>Number(await canvas.getAttribute('data-view-zoom'))).toBeLessThan(100);
  await page.getByRole('button',{name:'Reset view zoom'}).click();await checkZoom('100');
  for(let i=0;i<9&&await page.getByRole('button',{name:'Zoom in view',exact:true}).isEnabled();i++)await page.getByRole('button',{name:'Zoom in view',exact:true}).click();
  await checkZoom('300');await expect(page.getByRole('button',{name:'Zoom in view',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Zoom out view',exact:true}).click();await checkZoom('250');
  for(let i=0;i<10&&await page.getByRole('button',{name:'Zoom out view',exact:true}).isEnabled();i++)await page.getByRole('button',{name:'Zoom out view',exact:true}).click();
  await checkZoom('65');await expect(page.getByRole('button',{name:'Zoom out view',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Reset view zoom'}).click();await checkZoom('100');
  await page.keyboard.down('w');await expect(position).not.toHaveText(start);await page.keyboard.up('w');
  await page.waitForTimeout(200);const walked=await position.textContent();update?.({...world,version:world.version+1});
  await page.waitForTimeout(300);await expect(position).toHaveText(walked!);
  await page.getByRole('button',{name:'World map',exact:true}).click();
  await expect(page.getByRole('button',{name:/Mira.*Follow/})).toBeVisible();
  await expect(page.getByRole('button',{name:/Orion.*Follow/})).toHaveCount(0);
  await page.getByRole('button',{name:/Mira.*Follow/}).click();await expect(page.locator('.world-location h2')).toHaveText('Mira');
  await page.getByRole('button',{name:'Zoom in view',exact:true}).click();await checkZoom('120');await expect(page.locator('.world-location h2')).toHaveText('Mira');
  await expect.poll(async()=>Number((await position.textContent())?.split(',')[0])).toBeGreaterThan(center+2);
  await expect.poll(()=>!!update).toBe(true);
  update!({...world,minute:721,version:world.version+2,agents:[{...world.agents[0],x:center+8},world.agents[1]]});
  await expect(page.locator('.world-hud strong')).toContainText('12:01');
  await expect.poll(async()=>Number((await position.textContent())?.split(',')[0]),{timeout:15000}).toBeGreaterThan(center+9);
  await page.keyboard.down('w');await expect(page.getByRole('button',{name:'Stop following',exact:true})).toHaveCount(0);await page.keyboard.up('w');
  await page.getByRole('button',{name:'World map',exact:true}).click();await page.getByRole('button',{name:'All residents',exact:true}).click();
  await page.getByRole('button',{name:/Orion.*Follow/}).click();await expect(page.locator('.world-location h2')).toHaveText('Orion');
  await expect(page.getByRole('button',{name:'Stop following',exact:true})).toHaveCount(1);
  await page.getByRole('button',{name:'Stop following',exact:true}).click();
  await page.getByRole('button',{name:'World map',exact:true}).click();
  await page.locator('.map-destination').filter({hasText:'Visit →'}).first().click();await expect(page.getByLabel('World map and residents')).toHaveCount(0);
  const visited=world.buildings[0];
  await expect.poll(async()=>{const [x,z]=(await position.textContent())!.split(',').map(Number);return Math.hypot(x-visited.x,z-visited.z);}).toBeLessThan(16);
  await expect(page.locator('.world-selection')).toHaveCount(0);
  await page.screenshot({path:testInfo.outputPath('first-person.png')});
  await page.getByRole('button',{name:'World map',exact:true}).click();await page.screenshot({path:testInfo.outputPath('world-map.png')});
  await page.keyboard.press('Escape');await expect(dialog).toBeVisible();
  await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('heading',{name:'Life, unfolding.'})).toBeVisible();
  await page.setViewportSize({width:390,height:844});await page.getByRole('button',{name:'Enter the world'}).click();await expect(dialog).toBeVisible();
  await expect(canvas).toHaveAttribute('data-controls-ready','true');
  await page.getByRole('button',{name:'Zoom in view',exact:true}).click();await checkZoom('120');
  const touch=await page.context().newCDPSession(page);
  await touch.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:2});
  await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:145,y:320,id:0},{x:245,y:320,id:1}]});
  await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:115,y:320,id:0},{x:275,y:320,id:1}]});
  await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await expect.poll(async()=>Number(await canvas.getAttribute('data-view-zoom'))).toBeGreaterThan(150);
  await touch.detach();
  await page.screenshot({path:testInfo.outputPath('first-person-mobile-zoom.png')});
  await page.getByRole('button',{name:'World map',exact:true}).click();await expect(page.getByLabel('World map and residents')).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('world-map-mobile.png')});
  await page.getByRole('button',{name:'Back to dashboard'}).click();await expect(dialog).toHaveCount(0);
  expect(errors).toEqual([]);
});

